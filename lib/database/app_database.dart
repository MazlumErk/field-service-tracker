/// Fills a freshly created database. Implemented by `DemoSeeder`; kept as a
/// callback so the database does not depend on the seed code.
typedef DatabaseSeeder = Future<void> Function(AppDatabase database);

/// The single SQLite database of the app.
///
/// * `PRAGMA foreign_keys = ON` is set on every open (SQLite default is off).
/// * [seeder] runs exactly once: when the database file is first created.
///   Reopening never re-seeds, so user changes persist until a demo reset.
@DriftDatabase(
  tables: [Customers, Devices, MaintenanceRecords, FilterReplacements],
  daos: [CustomersDao, DevicesDao, MaintenanceDao],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase(super.executor, {this.seeder});

  /// Opens the on-device database file `field_service_tracker.sqlite`.
  factory AppDatabase.open({DatabaseSeeder? seeder}) =>
      AppDatabase(driftDatabase(name: databaseName), seeder: seeder);

  static const String databaseName = 'field_service_tracker';

  final DatabaseSeeder? seeder;

  /// Bump on every schema change, add a migration step and run
  /// `dart run drift_dev make-migrations` (see docs/DATABASE.md).
  @override
  int get schemaVersion => 1;

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (m) => m.createAll(),
    onUpgrade: (m, from, to) async {
      // Version 1 is the first released schema; future versions add
      // `stepByStep` migrations generated by drift_dev here.
      throw UnsupportedError('No migration path from v$from to v$to');
    },
    beforeOpen: (details) async {
      await customStatement('PRAGMA foreign_keys = ON');
      if (details.wasCreated) {
        await seeder?.call(this);
      }
    },
  );

  /// Reads `PRAGMA foreign_keys` (1 = enforced). Used by tests and startup
  /// diagnostics.
  Future<bool> foreignKeysEnabled() async {
    final row = await customSelect('PRAGMA foreign_keys').getSingle();
    return row.read<int>('foreign_keys') == 1;
  }

  /// Deletes every row of every table and resets AUTOINCREMENT counters,
  /// children first so foreign keys stay satisfied. Caller provides the
  /// transaction.
  Future<void> deleteAllData() async {
    await delete(filterReplacements).go();
    await delete(maintenanceRecords).go();
    await delete(devices).go();
    await delete(customers).go();
    await customStatement('DELETE FROM sqlite_sequence');
  }
}
